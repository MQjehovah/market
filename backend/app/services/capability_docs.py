ERP_DOC = """# ERP

访问公司 ERP 业务数据。

## 访问方式

- **普通员工**：必须配置自己的 ERP 账号密码；没有个人凭据时请求会被拒绝。
- **管理员/领导**：可以不配置个人凭据，使用平台兜底凭据执行；该凭据仅管理员可用。
- 平台兜底不会让普通用户绕过个人凭据。

## 配置个人凭据

1. 加入「ERP」能力；
2. 打开能力详情页「配置」（或 Agent 能力市场的「配置凭据」）；
3. 在「个人凭据」中填写 ERP 用户名、密码；
4. 保存后在对话中使用。

## 配置平台兜底凭据

仅作者/管理员可见「平台兜底凭据」，填写高权限 ERP 账号后保存。该凭据只用于管理员/系统任务在个人凭据缺失时兜底，并单独记录审计。

## 怎么用

- 「查一下上个月的销售订单」
- 「这个客户还有多少应收」
- 「查库存和发货状态」

## 注意

ERP 权限由 ERP 账号本身决定；平台兜底使用的是高权限账号，管理员操作会被记录为平台兜底执行。
"""

DOCS = {
    "dingtalk-dws": DWS_DOC,
    "dingtalk-openapi": OPENAPI_DOC,
    "erp": ERP_DOC,
}


async def ensure_capability_docs(db: AsyncSession) -> None:
    """为已知平台能力补齐说明；按能力名覆盖为维护版本。"""
    for name, doc in DOCS.items():
        rows = (
            await db.scalars(
                select(Capability).where(
                    Capability.name == name,
                    Capability.status.in_(("published", "deprecated")),
                )
            )
        ).all()
        for row in rows:
            row.readme_md = doc
        if rows:
            logger.info("已更新能力说明: %s (%d 个版本)", name, len(rows))
